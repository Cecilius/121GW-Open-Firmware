"""Induced emulator test of the USART2 overrun flag with RXNE = 0 (firmware OF-71, ble/usart.s ble_usart2_isr).

    python -I emulator/scripts/test_ble_overrun.py [image]          default firmware/build/EEVBlog.bin

RM0038 27.3.3: the RXNEIE interrupt is also generated by ORE, and ORE can be set while RXNE = 0 ("the new data is
received during the reading sequence, between the USART_SR register read access and the USART_DR read access"); only
a read of SR followed by a read of DR clears it.  A receive interrupt that returns when RXNE = 0 without reading DR
(v2.05 and firmware before F-1.15) is raised again at once for ever.

The state is put in place with the USART model's own rules (emu/periph/usart.py): the NVIC enable bit of IRQ 38 is
cleared, a byte A arrives (RXNE = 1), the sequence "read SR" is done, a byte B arrives (ORE = 1, RXNE still 1), then
"read DR" returns A and clears RXNE and the flags the SR read had seen, so ORE (set after the SR read) stays set with
RXNE = 0.  The IRQ is then enabled again.
  T1 the state RXNE = 0, ORE = 1, RXNEIE = 1 is reached
  T2 within 50 ms the firmware has read DR and ORE is clear (without the fix ORE stays set: the interrupt storm)
  T3 the meter is alive: a version request (F4 39 30 39 30) is echoed and answered, status frames come again
  T4 a normal byte received afterwards is parsed (the same request answered a second time)
The helpers are those of test_backlight_timer.py.
"""
import os
import sys

sys.dont_write_bytecode = True                       # keep the tree free of __pycache__
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import test_backlight_timer as T  # noqa: E402
import test_ble_version as V  # noqa: E402

ADDR_BLE_ON = 0x2000802B
SR_RXNE, SR_ORE = 0x20, 0x08
IRQ = 38                                             # USART2 (RM0038 table 51)


def sr(e):
    return e.usart2.sr


def irq_enable(e, on):
    """NVIC_ISER / ICER bit of IRQ 38 (the model keeps the enable bits in nvic.iser)."""
    if on:
        e.m.nvic.iser[IRQ >> 5] |= 1 << (IRQ & 31)
    else:
        e.m.nvic.iser[IRQ >> 5] &= ~(1 << (IRQ & 31))


def run_tests(image):
    e = T.make(image)
    e.command({'dial': 2})
    e.advance(3.0)
    T.long_press(e, 'PEAK')
    e.advance(1.0)
    T.check('Bluetooth on', T.rd(e, ADDR_BLE_ON) == 1)

    print('T1 ORE set while RXNE = 0 (a byte arrived between the SR read and the DR read)')
    irq_enable(e, False)
    e.advance(0.05)                                  # a running transmission may finish its byte; the handler is off
    e.usart2.rx_feed(0x11)                           # byte A
    e.advance(0.02)
    T.check('byte A in RDR: RXNE = 1, ORE = 0', sr(e) & (SR_RXNE | SR_ORE) == SR_RXNE, 'SR 0x%04X' % sr(e))
    e.usart2.read(0x00, 2)                           # "read SR" (first half of the clearing sequence)
    e.usart2.rx_feed(0x22)                           # byte B arrives before DR is read
    e.advance(0.02)
    T.check('byte B overran: ORE = 1, RXNE = 1', sr(e) & (SR_RXNE | SR_ORE) == SR_RXNE | SR_ORE, 'SR 0x%04X' % sr(e))
    a = e.usart2.read(0x04, 2) & 0xFF                # "read DR": returns A
    T.check('DR returned byte A (0x11)', a == 0x11, '0x%02X' % a)
    T.check('now RXNE = 0 and ORE = 1', sr(e) & (SR_RXNE | SR_ORE) == SR_ORE, 'SR 0x%04X' % sr(e))
    T.check('RXNEIE set', e.usart2.cr1 & 0x20 != 0, 'CR1 0x%04X' % e.usart2.cr1)

    print('T2 the firmware clears it')
    n0 = len(e.ble_rx)
    irq_enable(e, True)
    e.advance(0.05)
    T.check('ORE cleared within 50 ms (without the fix it stays set: interrupt storm)', sr(e) & SR_ORE == 0,
            'SR 0x%04X' % sr(e))

    print('T3 the meter is alive')
    e.advance(1.0)
    T.check('status frames come again', bytes(e.ble_rx[n0:]).count(b'\xF2') > 0)
    n0 = len(e.ble_rx)
    e.usart2.rx_feed(b'\xF4' + b'9090')
    e.advance(1.0)
    got = V.frames_after(e, n0)
    want = V.expected_version(image)
    T.check('version request echoed and answered', got == b'\xF4' + b'9090' + want, 'got %r' % got)

    print('T4 normal reception afterwards')
    n0 = len(e.ble_rx)
    e.usart2.rx_feed(b'\xF4' + b'9090')
    e.advance(1.0)
    got = V.frames_after(e, n0)
    T.check('the same request answered a second time', got == b'\xF4' + b'9090' + want, 'got %r' % got)
    s = e.snapshot()
    T.check('no unmodelled access, no safety violation', s['unmodelled'] == 0 and not s['safety'])


def main(argv):
    image = argv[0] if argv else os.path.join(T.ROOT, 'firmware', 'build', 'EEVBlog.bin')
    run_tests(image)
    print('RESULT', ('FAIL: ' + ', '.join(T.fails)) if T.fails else 'ALL PASS', flush=True)
    return 1 if T.fails else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
